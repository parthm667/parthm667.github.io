/**
 * Builds public/goose-chase/chase-data.js from the (gitignored) stage definitions.
 *
 *   node tools/build-goose-chase.mjs
 *
 * Every stage after the first is encrypted with AES-GCM using a key derived
 * (PBKDF2-SHA256) from the PREVIOUS stage's code. A student therefore cannot
 * read stage N's puzzle, or its hint, until they have solved stage N-1, and
 * no code appears in plaintext in anything we publish.
 *
 * The browser half of this lives in public/goose-chase/script.js and must keep
 * using the same normalisation, iteration count and cipher.
 */
import { webcrypto as crypto } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "../public/goose-chase/chase-data.js");

const { stages, iterations } = await import("./goose-chase-stages.mjs").catch(() => {
  console.error(
    "Missing tools/goose-chase-stages.mjs (it is gitignored because it holds the answer key).\n" +
      "Restore your local copy before building."
  );
  process.exit(1);
});

/** Codes are compared loosely: case, spaces and dashes never matter. */
const normalise = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const b64 = (buf) => Buffer.from(buf).toString("base64");
const encoder = new TextEncoder();

async function deriveKey(code, salt) {
  const material = await crypto.subtle.importKey(
    "raw",
    encoder.encode(normalise(code)),
    "PBKDF2",
    false,
    ["deriveKey"]
  );
  return crypto.subtle.deriveKey(
    { name: "PBKDF2", salt, iterations, hash: "SHA-256" },
    material,
    { name: "AES-GCM", length: 256 },
    false,
    ["encrypt", "decrypt"]
  );
}

async function seal(payload, code) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const key = await deriveKey(code, salt);
  const ct = await crypto.subtle.encrypt(
    { name: "AES-GCM", iv },
    key,
    encoder.encode(JSON.stringify(payload))
  );
  return { s: b64(salt), iv: b64(iv), ct: b64(ct) };
}

const blobs = [];
for (let i = 1; i < stages.length; i++) {
  const stage = stages[i];
  const unlockedBy = stages[i - 1].code;
  const payload = {
    n: i + 1,
    victory: Boolean(stage.victory),
    title: stage.title,
    hint: stage.hint ?? "",
    html: stage.html.trim(),
    css: (stage.css ?? "").trim(),
    // The code just proved correct, shown back so students can copy it to the form.
    confirmed: unlockedBy,
  };
  blobs.push(await seal(payload, unlockedBy));
}

const banner =
  "// Generated by tools/build-goose-chase.mjs. Do not edit by hand.\n" +
  "// Each blob is AES-GCM ciphertext; the key comes from the previous stage's code.\n" +
  "// There is nothing readable in here without solving the chase. Nice try, though.\n";

writeFileSync(
  OUT,
  `${banner}window.CHASE_DATA = ${JSON.stringify({ it: iterations, blobs }, null, 1)};\n`,
  "utf8"
);

console.log(`Wrote ${OUT}`);
console.log(`${blobs.length} sealed stages (${stages.length - 1} unlockable, last one is the victory card).`);
