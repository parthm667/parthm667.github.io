import { test, expect } from '@playwright/test'

const screen = page => page.locator('.xterm-rows')
const panel = page => page.getByRole('region', { name: 'linux terminal' })
const introHint = 'prefer clicking around? switch to file explorer in the top left.'

async function expectIntroHint(page) {
  const transcript = (await screen(page).innerText()).replace(/\s/g, '')
  const hint = introHint.replace(/\s/g, '')
  expect(transcript).toContain(hint)
  expect(transcript.indexOf(hint)).toBeLessThan(transcript.indexOf('catabout.txt'))
}

async function ready(page) {
  await expect(panel(page)).toHaveAttribute('data-booting', 'false')
}

async function command(page, text) {
  await ready(page)
  await page.getByRole('textbox', { name: 'terminal command' }).focus()
  await page.keyboard.press('Control+u')
  await page.keyboard.type(text)
  await page.keyboard.press('Enter')
}

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
})

test('terminal uses a full-screen character grid and compact shell output', async ({ page }, info) => {
  await ready(page)
  await expect(screen(page)).toContainText('parth@portfolio:~$')
  await expect(screen(page)).toContainText('projects')
  await expect(screen(page)).not.toContainText('permissions')
  await expect(screen(page)).not.toContainText('directory:')
  await expect(panel(page).locator('h1, table, .terminal-input-row')).toHaveCount(0)
  const bounds = await page.locator('.desktop').boundingBox()
  expect(bounds).toMatchObject({ x: 0, y: 0, width: page.viewportSize().width, height: page.viewportSize().height })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight)).toBe(true)
  await page.screenshot({ path: info.outputPath('terminal.png'), fullPage: true })
  await page.getByRole('button', { name: 'file explorer', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'home', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'grid view' })).toHaveAttribute('aria-pressed', 'true')
  const files = page.locator('.explorer-files')
  await expect(files.locator('img')).toHaveCount(8)
  await expect.poll(() => files.locator('img').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0))).toBe(true)
  expect(await page.locator('.explorer-panel').evaluate(el => getComputedStyle(el).fontFamily)).toContain('Ubuntu')
  await expect(page.locator('.sidebar-bottom, .explorer-toolbar')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('explorer.png'), fullPage: true })
})

test('commands navigate, complete, read files, recall history, and clear', async ({ page }) => {
  await ready(page)
  await page.getByRole('textbox', { name: 'terminal command' }).focus()
  await page.keyboard.type('cd proj')
  await page.keyboard.press('Tab')
  await expect(screen(page)).toContainText('cd projects/')
  await page.keyboard.press('Enter')
  await command(page, 'pwd')
  await expect(screen(page)).toContainText('/home/parth/projects')
  await command(page, 'cd order-book')
  await command(page, 'cat readme.md')
  await expect(screen(page)).toContainText('c++20 order book')
  await page.keyboard.press('ArrowUp')
  await expect(screen(page)).toContainText('cat readme.md')
  await page.keyboard.press('ArrowDown')
  await command(page, 'clear')
  await expect(screen(page)).not.toContainText('c++20 order book')
  await expect(screen(page)).toContainText('parth@portfolio:~/projects/order-book$')
  await command(page, 'tree ~')
  await expect(screen(page)).toContainText('photography.url')
  await command(page, 'pwd')
  await expect(screen(page)).toContainText('/home/parth/projects/order-book')
})

