test('startup types into the same buffer and does not replay', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.clock.install()
  await page.reload()
  await expect(panel(page)).toHaveAttribute('data-booting', 'true')
  await expect(screen(page)).toContainText('prefer clicking around?')
  const first = await screen(page).innerText()
  await page.clock.runFor(200)
  expect((await screen(page).innerText()).length).toBeGreaterThan(first.length)
  await page.clock.runFor(4000)
  await ready(page)
  await expect(screen(page)).toContainText('cat about.txt')
  await expectIntroHint(page)
  await page.getByRole('button', { name: 'file explorer', exact: true }).click()
  await page.getByRole('button', { name: 'terminal', exact: true }).click()
  await ready(page)
  await expect(page.getByRole('button', { name: /skip intro/ })).toHaveCount(0)
  await expectIntroHint(page)
  expect((await screen(page).innerText()).match(/prefer clicking around\?/g)).toHaveLength(1)
})

test('startup skips with a button or Escape and respects reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.clock.install()
  await page.reload()
  await page.getByRole('button', { name: /skip intro/ }).click()
  await ready(page)
  await expectIntroHint(page)
  await page.reload()
  await page.keyboard.press('Escape')
  await ready(page)
  await expectIntroHint(page)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.reload()
  await ready(page)
  await expectIntroHint(page)
  await expect(page.getByRole('button', { name: /skip intro/ })).toHaveCount(0)
})
