test('opening a file shows a dialog and Escape returns focus to the file', async ({ page }) => {
  await page.getByRole('button', { name: 'file explorer', exact: true }).click()
  const file = page.getByRole('button', { name: /^about.txt text document/ })
  await file.click()
  const preview = page.getByRole('dialog', { name: 'preview of about.txt' })
  await expect(preview).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(preview).not.toBeVisible()
  await expect(file).toBeFocused()
  if (page.viewportSize().width < 640) {
    await page.getByRole('button', { name: 'toggle folder sidebar' }).click()
    await page.getByRole('button', { name: 'open about.txt', exact: true }).click()
    await expect(preview).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(preview).not.toBeVisible()
    await expect(page.locator(':focus')).toBeVisible()
    expect(await page.locator(':focus').evaluate(el => el.tagName)).toBe('BUTTON')
  }
})

